import SwiftUI

struct TodayView: View {
    @Environment(AppStore.self) private var store
    var startQuiz: (QuizSession) -> Void
    var goTo: (AppSection) -> Void

    @State private var generating = false
    @State private var error: String?

    var body: some View {
        let p = store.profile
        let plan = store.dailyPlan()
        ScrollView {
            VStack(alignment: .leading, spacing: 24) {
                PageHeader(title: greeting, subtitle: GameEngine.levelTitle(p.level))

                HStack(spacing: 12) {
                    StatPill(symbol: "star.circle", value: "\(p.level)", label: "Level")
                    StatPill(symbol: "bolt.fill", value: p.totalXP.formatted(), label: "Total XP", tint: Theme.gold)
                    StatPill(symbol: "flame.fill", value: "\(p.currentStreak)", label: streakLabel, tint: Theme.gold)
                    StatPill(symbol: "books.vertical", value: "\(store.lectures.count)", label: "Lectures")
                }

                if !store.hasAPIKey {
                    Card {
                        Label("Add your Anthropic API key", systemImage: "key").font(.headline)
                        Text("Quizzes are generated by Claude. Open Settings (⌘,) and paste a key from console.anthropic.com.")
                            .foregroundStyle(.secondary)
                        SettingsLink { Text("Open Settings…") }
                    }
                }

                Card {
                    HStack {
                        Label("Daily Review", systemImage: "calendar").font(Theme.serif(20))
                        Spacer()
                        if store.dailyDoneToday {
                            Label("Done today", systemImage: "checkmark.circle.fill").foregroundStyle(Theme.success)
                        }
                    }
                    if plan.isEmpty {
                        Text(store.topicStats.isEmpty
                             ? "Take a lecture quiz first — LectureQuest then schedules each topic for spaced-repetition review."
                             : "You're all caught up. Nothing is due for review today.")
                            .foregroundStyle(.secondary)
                    } else {
                        Text("\(plan.count) topic\(plan.count == 1 ? "" : "s") picked by spaced repetition (SM-2). 10 active-recall questions.")
                            .foregroundStyle(.secondary)
                        FlowLayout(spacing: 6) {
                            ForEach(plan, id: \.self) { t in
                                Text(t.topic)
                                    .font(.caption)
                                    .padding(.horizontal, 8).padding(.vertical, 4)
                                    .background(reasonColor(t.reason).opacity(0.15), in: Capsule())
                                    .help("\(t.lectureTitle) · \(t.reason.rawValue)")
                            }
                        }
                        HStack {
                            Button {
                                Task { await startDaily(plan) }
                            } label: {
                                if generating { ProgressView().controlSize(.small) } else { Text("Start Daily Review") }
                            }
                            .buttonStyle(.borderedProminent)
                            .disabled(generating || !store.hasAPIKey)
                            if let error { Text(error).font(.caption).foregroundStyle(.red).lineLimit(2) }
                        }
                    }
                }

                PowerUpsCard()

                Card {
                    HStack {
                        Text("Needs review").font(Theme.serif(20))
                        Spacer()
                        Button("Add lectures") { goTo(.importer) }
                    }
                    let review = store.lectures.filter(\.needsReview).prefix(6)
                    if review.isEmpty {
                        Text(store.lectures.isEmpty ? "Add your first lecture (PDF, text or Markdown) to get started."
                                                    : "Every lecture is at 80%+ — nice.")
                            .foregroundStyle(.secondary)
                    }
                    ForEach(Array(review)) { l in
                        LectureRow(lecture: l, startQuiz: startQuiz)
                        Divider()
                    }
                }
            }
            .padding(32)
            .frame(maxWidth: 900)
            .frame(maxWidth: .infinity)
        }
    }

    private var greeting: String {
        let h = Calendar.current.component(.hour, from: .now)
        let part = h < 12 ? "Good morning" : h < 18 ? "Good afternoon" : "Good evening"
        let first = store.profile.displayName.split(separator: " ").first.map(String.init) ?? ""
        return first.isEmpty ? part : "\(part), \(first)"
    }

    private var streakLabel: String {
        if let m = GameEngine.streakMultiplierLabel(store.profile.currentStreak) { return "Day streak · \(m)" }
        return "Day streak"
    }

    private func reasonColor(_ r: ReviewReason) -> Color {
        switch r {
        case .overdue: .red
        case .weak: Theme.gold
        case .new: .purple
        case .due: Theme.forest
        }
    }

    private func startDaily(_ plan: [PlannedTopic]) async {
        generating = true; error = nil
        defer { generating = false }
        do { startQuiz(try await store.startDailyQuiz(plan)) }
        catch { self.error = error.localizedDescription }
    }
}

struct PowerUpsCard: View {
    @Environment(AppStore.self) private var store
    var body: some View {
        let pu = store.profile.powerUps
        Card {
            Text("Power-ups").font(Theme.serif(20))
            HStack(spacing: 12) {
                StatPill(symbol: "lightbulb", value: "\(pu.hints)", label: "Hints · remove 2 wrong answers", tint: Theme.gold)
                StatPill(symbol: "arrow.uturn.backward.circle", value: "\(pu.secondChance)", label: "Second chances · earn with 100%")
                VStack(alignment: .leading) {
                    if pu.doubleXP {
                        Label("Double XP active", systemImage: "bolt.badge.checkmark").foregroundStyle(Theme.gold)
                    } else {
                        Text("Double XP").font(.subheadline)
                        Text("Random level-up reward").font(.caption).foregroundStyle(.secondary)
                    }
                }
                .padding(.horizontal, 14).padding(.vertical, 10)
                .frame(maxWidth: .infinity, alignment: .leading)
                .background(.background.secondary, in: RoundedRectangle(cornerRadius: 12))
            }
        }
    }
}

/// Simple wrapping layout for topic chips.
struct FlowLayout: Layout {
    var spacing: CGFloat = 8

    func sizeThatFits(proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) -> CGSize {
        let width = proposal.width ?? .infinity
        var x: CGFloat = 0, y: CGFloat = 0, rowH: CGFloat = 0, maxX: CGFloat = 0
        for v in subviews {
            let s = v.sizeThatFits(.unspecified)
            if x > 0 && x + s.width > width { x = 0; y += rowH + spacing; rowH = 0 }
            x += s.width + spacing
            rowH = max(rowH, s.height)
            maxX = max(maxX, x)
        }
        return CGSize(width: min(maxX, width), height: y + rowH)
    }

    func placeSubviews(in bounds: CGRect, proposal: ProposedViewSize, subviews: Subviews, cache: inout ()) {
        var x = bounds.minX, y = bounds.minY, rowH: CGFloat = 0
        for v in subviews {
            let s = v.sizeThatFits(.unspecified)
            if x > bounds.minX && x + s.width > bounds.maxX { x = bounds.minX; y += rowH + spacing; rowH = 0 }
            v.place(at: CGPoint(x: x, y: y), proposal: ProposedViewSize(s))
            x += s.width + spacing
            rowH = max(rowH, s.height)
        }
    }
}
